#!/usr/bin/env python3
"""Convert packMP3's C lookup-table headers into Go source.

Usage: python3 convtables.py <packMP3/source dir> <out dir>

Only static array declarations with brace initializers are converted.
Every table becomes a Go slice (nested slices for multi-dim arrays), so
C pointer arithmetic like `tab + 16` maps to `tab[16:]`.
"""
import re
import subprocess
import sys
from pathlib import Path

TYPES = {
    "int": "int",
    "unsigned int": "uint32",
    "unsigned char": "uint8",
    "char": "int8",
    "unsigned short": "uint16",
    "signed short": "int16",
    "short": "int16",
    "huffman_code": "huffmanCode",
    "huffman_code*": "[]huffmanCode",
    "int*": "[]int",
    "char*": "string",
    "huffman_conv": "huffmanConv",
    "huffman_conv_set": "huffmanConvSet",
    "huffman_enc_table": "huffmanEncTable",
    "huffman_dec_table": "huffmanDecTable",
}

DEFINES = {"MP3_V2_5": "0", "MP3_V2_0": "2", "MP3_V1_0": "3",
           "LAYER_III": "1", "LAYER_II": "2", "LAYER_I": "3"}

DECL = re.compile(
    r"static\s+(?:const\s+)?((?:unsigned\s+|signed\s+)?\w+\s*\*?)\s*(\w+)((?:\s*\[[^\]]*\])+)\s*=\s*(\{.*?\})\s*;",
    re.S,
)


def camel(name):
    head, *rest = name.split("_")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def parse(body):
    """Parse a C brace initializer into nested lists of scalar strings."""
    toks = re.findall(r'"[^"]*"|[{},]|[^{},]+', body)
    toks = [t.strip() for t in toks if t.strip()]
    pos = 0

    def group():
        nonlocal pos
        assert toks[pos] == "{"
        pos += 1
        items = []
        while toks[pos] != "}":
            if toks[pos] == "{":
                items.append(group())
            elif toks[pos] != ",":
                items.append(toks[pos])
                pos += 1
            else:
                pos += 1
        pos += 1
        return items

    return group()


def pretty(node, depth=0):
    ind = "\t" * (depth + 1)
    if all(isinstance(x, str) for x in node):
        if len(node) <= 16 and depth > 0:
            return "{" + ", ".join(node) + "}"
        rows = [", ".join(node[i:i + 16]) + "," for i in range(0, len(node), 16)]
        return "{\n" + "".join(ind + r + "\n" for r in rows) + "\t" * depth + "}"
    return "{\n" + "".join(ind + pretty(x, depth + 1) + ",\n" if not isinstance(x, str)
                           else ind + x + ",\n" for x in node) + "\t" * depth + "}"


def strip(src):
    # drop DEV_BUILD-only blocks, comments and preprocessor lines
    src = re.sub(r"#if defined\(DEV_BUILD\).*?#endif", "", src, flags=re.S)
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    src = re.sub(r"//[^\n]*", "", src)
    return "\n".join(l for l in src.splitlines() if not l.lstrip().startswith("#"))


def convert(src, names):
    out = []
    for m in DECL.finditer(src):
        ctype, name, dims, body = m.groups()
        ctype = re.sub(r"\s+", " ", ctype.strip()).replace(" *", "*")
        if ctype not in TYPES:
            sys.exit(f"unknown type {ctype!r} for {name}")
        ndims = dims.count("[")
        body = re.sub(r"\s+", " ", body)
        # pointer arithmetic: name + N -> name[N:]
        body = re.sub(r"\b([a-z]\w*)\s*\+\s*(\d+)", lambda x: f"{camel(x.group(1))}[{x.group(2)}:]", body)
        for k, v in DEFINES.items():
            body = re.sub(rf"\b{k}\b", v, body)
        body = re.sub(r"\bNULL\b", "nil", body)
        body = re.sub(r"\b(htab\w+|[a-z]+_\w*table\w*)\b(?!\[)", lambda x: camel(x.group(1)), body)
        body = re.sub(r"\b([a-z]\w*_\w+)\b", lambda x: camel(x.group(1)), body)
        gotype = "[]" * ndims + TYPES[ctype]
        tree = parse(body)
        # C zero-fills arrays declared larger than their initializer; Go slices don't
        first = re.search(r"\[([^\]]*)\]", dims).group(1).strip()
        if first and all(isinstance(x, str) for x in tree):
            tree += ["0"] * (eval(first) - len(tree))
        out.append(f"var {camel(name)} = {gotype}{pretty(tree)}\n")
        names.append(name)
    return out


def main():
    srcdir, outdir = Path(sys.argv[1]), Path(sys.argv[2])
    for hdr, gofile in [("huffmp3tbl.h", "tables_huffman.go"),
                        ("pmp3tbl.h", "tables_pmp3.go"),
                        ("pmp3bitlen.h", "tables_bitlen.go")]:
        names = []
        decls = convert(strip((srcdir / hdr).read_text()), names)
        text = (f"// Code generated by tools/convtables.py from packMP3 {hdr}. DO NOT EDIT.\n\n"
                "package packmp3\n\n" + "\n".join(decls))
        path = outdir / gofile
        path.write_text(text)
        subprocess.run(["gofmt", "-w", str(path)], check=True)
        print(f"{hdr}: {len(names)} tables -> {gofile}")


if __name__ == "__main__":
    main()
